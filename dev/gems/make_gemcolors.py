def fetch(table, build):
    url = "https://wago.tools/db2/%s/csv" % table
    if build:
        url += "?build=" + build
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(request) as response:
        return list(csv.DictReader(io.StringIO(response.read().decode("utf-8"))))


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else None
    csv.field_size_limit(10 ** 8)
    gem_types = {row["ID"]: int(row["Type"]) for row in fetch("GemProperties", build)}

    colors, unknown = {}, set()
    for row in fetch("ItemSparse", build):
        properties = row["Gem_properties"]
        if properties in ("", "0") or int(row["ExpansionID"]) != EXPANSION:
            continue
        stone = row["Display_lang"].split()[-1]
        if stone in COLORS:
            colors[int(row["ID"])] = (COLORS[stone], row["Display_lang"])
        else:
            unknown.add("%s (%s, type %s)" % (row["Display_lang"], row["ID"], gem_types.get(properties)))

    if unknown:
        print("Unknown stones, add them to COLORS:")
        for line in sorted(unknown):
            print("  " + line)
        sys.exit(1)

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER % (build or "current, %s" % datetime.date.today()))
        for item_id in sorted(colors):
            color, name = colors[item_id]
            f.write('    [%d] = "%s", -- %s\n' % (item_id, color, name))
        f.write("};\n")
    print("%d gems written to %s" % (len(colors), OUTPUT))


if __name__ == "__main__":
    main()
